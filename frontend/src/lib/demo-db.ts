/** Simulates network latency so loading states are visible in the demo. */
export function delay(ms = 350): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

export function newId(prefix: string): string {
  return `${prefix}_${crypto.randomUUID().slice(0, 8)}`;
}

function withCounts(list: Vault[]): Vault[] {
  return list.map((vault) => ({
    ...vault,
    itemCount: items.filter((item) => item.vaultId === vault.id).length,
  }));
}

export const demoDb = {
  getVaults: () => withCounts(vaults),
  getVault: (id: string) => withCounts(vaults).find((v) => v.id === id),
  setVaults: (next: Vault[]) => {
    vaults = next;
  },
  getItems: () => [...items],
  setItems: (next: VaultItem[]) => {
    items = next;
  },
  getFolders: () => [...folders],
  setFolders: (next: Folder[]) => {
    folders = next;
  },
};
